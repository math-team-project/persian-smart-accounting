"""ساخت پرامپت سیستم و کاربر برای فراخوانی LLM.

راهبرد: به‌جای یک فراخوانی جداگانه برای هر سوال (که هزینه/تأخیر و ریسک
ناهماهنگی لحن را بالا می‌برد)، تمام موارد عدم تطابق در یک فراخوانی واحد
به مدل داده می‌شود و خروجی به‌صورت آرایه JSON ساختاریافته درخواست می‌شود.
این کار همچنین به مدل اجازه می‌دهد متن کامل گزارش حسابرسی را به‌عنوان
مرجع ببیند و مواردی که از قبل در آن گزارش ذکر شده‌اند را تشخیص دهد.
"""

from __future__ import annotations

import json
from typing import List

from .schemas import ChecklistItem, LoadedInput

SYSTEM_PROMPT = """\
تو دستیار یک مؤسسه حسابرسی هستی و وظیفه‌ات آماده‌سازی خلاصه‌ی «گزارش جهت جلسه کمیسیون/هیئت‌مدیره»
بر پایه‌ی دو منبع است:
 (۱) نتایج یک چک‌لیست خودکار حسابرسی که موارد «عدم تطابق» را مشخص کرده،
 (۲) متن کامل گزارش حسابرسی مستقل که ممکن است نکات مهمی داشته باشد که اصلاً در چک‌لیست
     خودکار پوشش داده نشده‌اند (مثل بند شرط یا تاکید حسابرس، ابهام در تداوم فعالیت،
     محدودیت در رسیدگی، عدم اطمینان‌های مهم، یادداشت‌های توضیحی حساس، تغییر رویه حسابداری،
     یا هر نکته‌ی مهم دیگری که حسابرس مستقل به آن اشاره کرده).

مخاطب این متن، اعضای کمیسیون هستند که عموماً پیش‌زمینه‌ی تخصصی حسابداری/حسابرسی ندارند.
بنابراین باید:
- از اصطلاحات فنی حسابداری تا حد امکان پرهیز کنی یا در صورت لزوم آن‌ها را در یک جمله‌ی
  بسیار ساده توضیح دهی.
- هر مورد را کوتاه، مستقیم و کاربردی بنویسی؛ نه یک توضیح تحلیلی بلند.
- روی «چه چیزی باید در جلسه مورد توجه/تصمیم‌گیری قرار گیرد» تمرکز کنی، نه شرح کامل
  روش محاسبه یا جزئیات فنی مغایرت.
- از افزودن هرگونه عدد یا ادعای جدیدی که در داده‌های ورودی نیامده خودداری کنی؛ فقط بر
  اساس همان اطلاعات ورودی خلاصه‌نویسی کن.
- زبان خروجی، فارسی رسمی و اداری باشد.

کار تو شامل دو بخش مجزاست:

### بخش اول — خلاصه‌ی موارد چک‌لیست (checklist_items)
برای هر مورد ورودی از چک‌لیست (که هرکدام یک question_id دارند)، یک خلاصه‌ی مدیریتی بساز.
اگر مضمون یک مورد در متن گزارش حسابرسی هم ذکر شده باشد، این را با
mentioned_in_audit_report=true مشخص کن تا در جلسه به‌عنوان موضوعی تکراری/تأییدشده
معرفی شود.

### بخش دوم — سایر نکات مهم گزارش حسابرسی (audit_report_findings)
متن کامل گزارش حسابرسی مستقل را با دقت مرور کن و نکات مهمی را که:
  - در چک‌لیست بالا اصلاً نیامده‌اند (یعنی هیچ question_id ای به آن‌ها اشاره نکرده)، و
  - از نظر یک عضو کمیسیون قابل توجه هستند (بندهای شرط/تاکید گزارش حسابرس، ابهامات،
    محدودیت‌های رسیدگی، تغییرات مهم رویه یا برآورد حسابداری، ریسک‌های قانونی/تعهدات،
    یا هر نکته‌ی بااهمیت دیگری که در متن گزارش صراحتاً ذکر شده)
استخراج و به همان شکل خلاصه و ساده در قالب آرایه‌ی audit_report_findings بیاور.
اگر گزارش حسابرسی نکته‌ی قابل‌توجه اضافه‌ای (فراتر از موارد چک‌لیست) نداشت، این آرایه را
خالی برگردان؛ نکته‌ای که صرفاً تکرار یکی از موارد چک‌لیست بالاست را دوباره در این بخش نیاور.

خروجی را **فقط و فقط** به‌صورت یک شیء (object) JSON معتبر برگردان (بدون هیچ متن اضافه، بدون
Markdown code fence، بدون توضیح قبل یا بعد از JSON)، دقیقاً با این ساختار:

{
  "checklist_items": [
    {
      "question_id": "<همان شناسه‌ی سوال>",
      "title": "<عنوان بسیار کوتاه موضوع، حداکثر ۸ تا ۱۰ کلمه>",
      "summary": "<۱ تا ۲ جمله‌ی ساده که می‌گوید مغایرت چیست، بدون جزئیات محاسباتی>",
      "committee_focus": "<۱ جمله که می‌گوید کمیسیون دقیقاً باید روی چه چیزی در جلسه تمرکز/تصمیم‌گیری کند>",
      "mentioned_in_audit_report": true/false,
      "severity": "کم" | "متوسط" | "بالا"
    }
  ],
  "audit_report_findings": [
    {
      "title": "<عنوان بسیار کوتاه نکته، حداکثر ۸ تا ۱۰ کلمه>",
      "summary": "<۱ تا ۲ جمله‌ی ساده درباره‌ی این نکته، بر اساس متن گزارش حسابرسی>",
      "committee_focus": "<۱ جمله که می‌گوید کمیسیون روی چه چیزی باید تمرکز/تصمیم‌گیری کند>",
      "severity": "کم" | "متوسط" | "بالا",
      "source_hint": "<اشاره‌ی بسیار کوتاه به بخش/یادداشت مرتبط در گزارش حسابرسی، مثلاً 'بند شرط گزارش' یا 'یادداشت ۱۲ صورت‌های مالی'؛ اگر مشخص نیست خالی بگذار>"
    }
  ]
}

تعیین severity: اگر مورد مربوط به اقلام کلان ترازنامه، تعهدات قانونی، بند شرط/عدم اظهارنظر
حسابرس، یا ابهام در تداوم فعالیت باشد، severity را "بالا" بگذار؛ مغایرت‌ها یا نکات جزئی/فرمی
را "کم" یا "متوسط" علامت بزن؛ در نبود قرینه‌ی روشن، "متوسط" منصفانه‌ترین انتخاب است.

تعداد اعضای checklist_items باید دقیقاً برابر تعداد موارد ورودی چک‌لیست باشد و ترتیب
question_id باید با ورودی یکسان بماند. اگر ورودی چک‌لیست خالی بود، checklist_items را
آرایه‌ی خالی بگذار اما بخش audit_report_findings را همچنان کامل انجام بده."""


def _format_key_figures(item: ChecklistItem) -> str:
    if not item.key_figures:
        return "(بدون داده عددی خاص)"
    parts = [f"{kf['name']} = {kf['value']}" for kf in item.key_figures]
    return "؛ ".join(parts)


def _format_checklist_items_block(items: List[ChecklistItem]) -> str:
    blocks = []
    for item in items:
        purpose = item.question_purpose.strip()
        if len(purpose) > 400:
            purpose = purpose[:400] + " ..."
        blocks.append(
            "\n".join(
                [
                    f"- question_id: {item.question_id}",
                    f"  question_text: {item.question_text}",
                    f"  message (نتیجه بررسی سیستم): {item.message or '(ثبت نشده)'}",
                    f"  key_figures: {_format_key_figures(item)}",
                    f"  question_purpose (خلاصه): {purpose or '(ثبت نشده)'}",
                ]
            )
        )
    return "\n\n".join(blocks)


def build_user_prompt(loaded: LoadedInput, max_doc_chars: int = 12000) -> str:
    doc_excerpt = loaded.doc_text
    truncated_note = ""
    if len(doc_excerpt) > max_doc_chars:
        doc_excerpt = doc_excerpt[:max_doc_chars]
        truncated_note = "\n[متن گزارش حسابرسی به دلیل طول زیاد، خلاصه/بریده شده است.]"

    if loaded.non_compliant_items:
        items_block = _format_checklist_items_block(loaded.non_compliant_items)
        items_intro = f"لیست موارد «عدم تطابق» شناسایی‌شده توسط چک‌لیست خودکار ({len(loaded.non_compliant_items)} مورد):"
    else:
        items_block = "(چک‌لیست خودکار در این دوره هیچ مورد عدم تطابقی گزارش نکرده است.)"
        items_intro = "لیست موارد «عدم تطابق» شناسایی‌شده توسط چک‌لیست خودکار:"

    return f"""\
متن کامل گزارش حسابرسی مستقل (این متن را با دقت کامل مرور کن؛ هم برای تشخیص همپوشانی
با چک‌لیست، و هم برای استخراج بخش دوم یعنی audit_report_findings استفاده می‌شود):
---
{doc_excerpt}{truncated_note}
---

{items_intro}
---
{items_block}
---

حالا خروجی JSON خواسته‌شده (شامل هر دو کلید checklist_items و audit_report_findings) را
طبق قالب تعیین‌شده در دستورالعمل سیستم تولید کن. یادت باشد بخش audit_report_findings را
مستقل از این‌که چک‌لیست خالی است یا نه، بر اساس مرور کامل متن گزارش حسابرسی تکمیل کنی."""


def build_messages(loaded: LoadedInput) -> List[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": build_user_prompt(loaded)},
    ]


