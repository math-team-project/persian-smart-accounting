def criteria_by_axis() -> dict[str, list[CriterionDefinition]]:
    """معیارها به تفکیک محور، با حفظ ترتیب تعریف (ترتیب نمایش در پرامپت)."""
    grouped: dict[str, list[CriterionDefinition]] = {}
    for criterion in DEFAULT_CRITERIA:
        grouped.setdefault(criterion.axis, []).append(criterion)
    return grouped


def axis_names() -> list[str]:
    """نام محورها به ترتیب تعریف -- بدون هیچ محدودیت عددی (قابل توسعه)."""
    return list(criteria_by_axis())


def criterion_ids() -> list[str]:
    return [criterion.criterion_id for criterion in DEFAULT_CRITERIA]


def criteria_prompt_block(extra: Sequence[CriterionDefinition] = ()) -> str:
    """متن آماده‌ی درج در پرامپت: همه‌ی محورها و معیارهای فعال.

    این تابع تنها جایی است که فهرست محورها به متن تبدیل می‌شود؛ افزودن معیار جدید
    هیچ تغییر دیگری لازم ندارد.
    """
    lines: list[str] = []
    for axis, criteria in criteria_by_axis().items():
        lines.append(f"### محور: {axis}")
        for criterion in criteria:
            lines.append(f"- **{criterion.name}** ({criterion.criterion_id})")
            lines.append(f"  - شرح: {criterion.description}")
            if criterion.data_requirements:
                lines.append("  - داده‌های موردنیاز: " + "؛ ".join(criterion.data_requirements))
            if criterion.calculation:
                lines.append(f"  - محاسبه: {criterion.calculation}")
            if criterion.threshold:
                lines.append(f"  - حد/مبنای مقایسه: {criterion.threshold}")
            if criterion.exceptions:
                lines.append("  - استثناها: " + "؛ ".join(criterion.exceptions))
            if criterion.severity_rule:
                lines.append(f"  - قاعده ثبت وضعیت: {criterion.severity_rule}")
        lines.append("")
    for criterion in extra:
        lines.append(f"- معیار اضافی: {criterion.name} ({criterion.criterion_id}) -- {criterion.description}")
    return "\n".join(lines).strip()
